def print_summary(results: list[dict]):
    print("\n" + "=" * 100)
    print("MULTI-MODEL FULL BATCH SUMMARY")
    print("=" * 100)
    print(f"{'Combo':<12} {'Q':<4} {'OK':<4} {'Iter':<6} {'Claims':<7} {'Open':<5} "
          f"{'AD':<4} {'T1':<4} {'T2':<4} {'T9':<4} {'Topology':<12} {'SynthConf'}")
    print("-" * 100)

    for r in results:
        ok    = "YES" if r["success"] else "NO"
        t1    = "Y" if r["t1_fired"] else "-"
        t2    = "Y" if r["t2_fired"] else "-"
        t9    = "Y" if r["t9_fired"] else "-"
        ad    = str(r.get("anti_delphi_activations", 0))
        topo  = r.get("topology", "?")
        sc    = f"{r.get('synthesis_confidence', 0):.3f}"
        print(f"{r['combo_id']:<12} {r['qid']:<4} {ok:<4} "
              f"{r['iterations']:<6} {r['claims_total']:<7} {r['claims_open']:<5} "
              f"{ad:<4} {t1:<4} {t2:<4} {t9:<4} {topo:<12} {sc}")

    print("-" * 100)
    n = len(results)
    if n == 0:
        return

    success_rate = sum(1 for r in results if r["success"]) / n * 100
    t1_rate      = sum(1 for r in results if r["t1_fired"]) / n * 100
    t2_rate      = sum(1 for r in results if r["t2_fired"]) / n * 100
    t9_rate      = sum(1 for r in results if r["t9_fired"]) / n * 100
    avg_claims   = sum(r["claims_total"] for r in results) / n
    avg_iter     = sum(r["iterations"] for r in results) / n
    total_open   = sum(r["claims_open"] for r in results)

    print(f"\nSuccess rate:    {success_rate:.0f}%")
    print(f"T1 fire rate:    {t1_rate:.0f}%")
    print(f"T2 fire rate:    {t2_rate:.0f}%")
    print(f"T9 fire rate:    {t9_rate:.0f}%")
    print(f"Avg claims/run:  {avg_claims:.1f}")
    print(f"Avg iter/run:    {avg_iter:.1f}")
    print(f"Total open:      {total_open}")

    # Topology distribution
    from collections import Counter
    topo_counts = Counter(r["topology"] for r in results)
    print(f"\nTopology distribution ({n} runs):")
    for topo, cnt in sorted(topo_counts.items()):
        print(f"  {topo:<12} {cnt:>3}  ({cnt/n*100:.0f}%)")

    # Per-combo aggregate
    print("\n" + "=" * 80)
    print("PER-COMBO AGGREGATE")
    print("-" * 80)
    print(f"{'Combo':<12} {'Runs':<6} {'OK':<4} {'AvgClaims':<11} {'AvgIter':<10} "
          f"{'T1%':<6} {'T2%':<6} {'Topo(C/T2/B/L)'}")
    print("-" * 80)
    combos_seen = list(dict.fromkeys(r["combo_id"] for r in results))
    for cid in combos_seen:
        sub = [r for r in results if r["combo_id"] == cid]
        ns   = len(sub)
        ok_s = sum(1 for r in sub if r["success"])
        avg_c = sum(r["claims_total"] for r in sub) / ns
        avg_i = sum(r["iterations"] for r in sub) / ns
        t1p   = sum(r["t1_fired"] for r in sub) / ns * 100
        t2p   = sum(r["t2_fired"] for r in sub) / ns * 100
        tc    = Counter(r["topology"] for r in sub)
        tstr  = f"{tc.get('contested',0)}/{tc.get('T2_path',0)}/{tc.get('branched',0)}/{tc.get('linear',0)}"
        print(f"{cid:<12} {ns:<6} {ok_s:<4} {avg_c:<11.1f} {avg_i:<10.1f} "
              f"{t1p:<6.0f} {t2p:<6.0f} {tstr}")

    print("\nISSUES:")
    issues = False
    for r in results:
        if not r["success"]:
            print(f"  FAIL {r['combo_id']}/{r['qid']}: {str(r.get('error',''))[:120]}")
            issues = True
        if r["claims_open"] > 0:
            print(f"  OPEN {r['combo_id']}/{r['qid']}: {r['claims_open']} unsealed")
            issues = True
    if not issues:
        print("  None.")

    with open(RESULTS_DIR / "summary.json", "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nFull results saved to: {RESULTS_DIR}/")


