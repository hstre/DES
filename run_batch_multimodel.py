if __name__ == "__main__":
    results = []
    for combo_id, bp, bm, fp, fm in COMBOS:
        for qid, question in QUESTIONS.items():
            run_key = f"{combo_id}_{qid}"
            existing = RESULTS_DIR / f"{run_key}.json"
            if existing.exists():
                print(f"  [skip] {run_key} already exists")
                with open(existing) as f:
                    results.append(json.load(f))
                continue
            try:
                r = run_single(combo_id, bp, bm, fp, fm, qid, question)
                results.append(r)
                status = "OK" if r["success"] else "FAIL"
                print(f"  -> {status} | {r['iterations']} iter | "
                      f"{r['claims_total']} claims | open={r['claims_open']} "
                      f"AD={r.get('anti_delphi_activations', 0)} "
                      f"T1={r['t1_fired']} T2={r['t2_fired']} T9={r['t9_fired']} "
                      f"topo={r['topology']}")
            except subprocess.TimeoutExpired:
                print(f"  -> TIMEOUT after 360s")
                results.append({
                    "combo_id": combo_id, "qid": qid, "question": question,
                    "builder_provider": bp, "builder_model": bm,
                    "falsifier_provider": fp, "falsifier_model": fm,
                    "success": False, "error": "timeout",
                    "transitions_fired": [], "t1_fired": False, "t2_fired": False,
                    "t9_fired": False, "claims_total": 0, "claims_open": 0,
                    "claims_sealed": 0, "claims_synthesis": 0, "claims_role_generated": 0,
                    "generated_by_counts": {}, "iterations": 0, "reframing_count": 0,
                    "anti_delphi_activations": 0, "elapsed_seconds": 360,
                    "topology": "linear", "contradiction_depth": 0,
                    "synthesis_confidence": 0.0,
                    "builder_t1_trigger": 0, "falsifier_t1_trigger": 0,
                })
            except Exception as e:
                print(f"  -> ERROR: {e}")

    print_summary(results)
