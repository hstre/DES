# ---------------------------------------------------------------------------
# Extended metric helpers
# ---------------------------------------------------------------------------

def classify_topology(claims: dict, transitions: list[str]) -> str:
    t1 = "T1" in transitions
    t2 = "T2" in transitions
    t4 = "T4" in transitions
    t9 = "T9" in transitions
    if t1 and t9:
        return "contested"
    elif t2 and not t1:
        return "T2_path"
    elif t4 and not t1:
        return "branched"
    else:
        return "linear"


def avg_synthesis_confidence(claims: dict) -> float:
    synth = [c["confidence"] for c in claims.values() if c.get("is_synthesis")]
    return round(sum(synth) / len(synth), 3) if synth else 0.0


def count_branch_levels(claims: dict) -> int:
    return sum(1 for c in claims.values() if c.get("branch_open"))


def count_role_triggers(claims: dict, op_history: list[str]) -> tuple[int, int]:
    """Return (builder_t1_triggers, falsifier_t1_triggers).

    A T1 trigger is attributed to a role if the claim that caused T1 was
    generated by that role (determined via generated_by field).
    """
    builder = 0
    falsifier = 0
    # Build map: claim_id → generated_by
    gb_map = {cid: c.get("generated_by", "") for cid, c in claims.items()}
    for op in op_history:
        if op.startswith("T1 on "):
            parent_id = op.split("T1 on ")[-1].strip()
            # T1 fires on a claim whose counter was generated by a role
            # Look for the most recent T5[role] op that references parent_id
            pass
    # Simpler: count role claims that triggered contradiction (status=contradicted parent)
    for cid, c in claims.items():
        gb = c.get("generated_by", "")
        if not gb:
            continue
        pid = c.get("parent_id")
        if pid and claims.get(pid, {}).get("status") == "contradicted":
            if "[hypothesis_builder]" in gb:
                builder += 1
            elif "[falsifier]" in gb:
                falsifier += 1
    return builder, falsifier


# ---------------------------------------------------------------------------
# Single run
# ---------------------------------------------------------------------------

def run_single(combo_id: str, bp: str, bm: str, fp: str, fm: str,
               qid: str, question: str) -> dict:
    print(f"\n{'='*70}")
    print(f"Running {combo_id} / {qid}: builder={bm} | falsifier={fm}")
    print(f"  Q: {question}")
    print("=" * 70)

    subprocess.run(["python", "des.py", "--reset"], capture_output=True, env=os.environ)

    cmd = [
        "python", "des.py", question,
        "--max-iter", "60",
        "--anti-delphi",
        "--builder-provider", bp,
        "--builder-model", bm,
        "--falsifier-provider", fp,
        "--falsifier-model", fm,
    ]
    start = time.time()
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=360, env=os.environ)
    elapsed = time.time() - start

    state_data = {}
    if Path("des_state.json").exists():
        with open("des_state.json") as f:
            state_data = json.load(f)

    claims = state_data.get("claims", {})
    op_history = state_data.get("operation_history", [])
    transitions_fired = sorted(set(
        op.split("[")[0].split(" ")[0]
        for op in op_history if op
    ))

    sealed_count    = sum(1 for c in claims.values() if c.get("sealed"))
    open_count      = sum(1 for c in claims.values() if not c.get("sealed"))
    role_count      = sum(1 for c in claims.values() if c.get("is_role_generated"))
    synthesis_count = sum(1 for c in claims.values() if c.get("is_synthesis"))

    generated_by_counts: dict[str, int] = {}
    for c in claims.values():
        gb = c.get("generated_by", "")
        if gb:
            generated_by_counts[gb] = generated_by_counts.get(gb, 0) + 1

    builder_t1, falsifier_t1 = count_role_triggers(claims, op_history)
    topology = classify_topology(claims, transitions_fired)
    synth_conf = avg_synthesis_confidence(claims)
    branch_depth = count_branch_levels(claims)

    result_data = {
        "combo_id": combo_id,
        "qid": qid,
        "question": question,
        "builder_provider": bp,
        "builder_model": bm,
        "falsifier_provider": fp,
        "falsifier_model": fm,
        "success": result.returncode == 0,
        "elapsed_seconds": round(elapsed, 1),
        "iterations": state_data.get("iteration", 0),
        "claims_total": len(claims),
        "claims_sealed": sealed_count,
        "claims_open": open_count,
        "claims_synthesis": synthesis_count,
        "claims_role_generated": role_count,
        "generated_by_counts": generated_by_counts,
        "transitions_fired": transitions_fired,
        "t1_fired": "T1" in transitions_fired,
        "t2_fired": "T2" in transitions_fired,
        "t9_fired": "T9" in transitions_fired,
        "reframing_count": state_data.get("reframing_count", 0),
        "anti_delphi_activations": state_data.get("anti_delphi_activations", 0),
        "topology": topology,
        "contradiction_depth": branch_depth,
        "synthesis_confidence": synth_conf,
        "builder_t1_trigger": builder_t1,
        "falsifier_t1_trigger": falsifier_t1,
        "error": result.stderr[-500:] if result.returncode != 0 else None,
        "stdout_tail": result.stdout[-800:],
    }

    run_key = f"{combo_id}_{qid}"
    with open(RESULTS_DIR / f"{run_key}.json", "w") as f:
        json.dump(result_data, f, indent=2)
    if Path("des_state.json").exists():
        shutil.copy("des_state.json", RESULTS_DIR / f"{run_key}_state.json")

    return result_data


